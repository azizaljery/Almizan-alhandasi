import test from 'node:test';
import assert from 'node:assert/strict';
import { mkdtempSync, mkdirSync, writeFileSync, copyFileSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { spawnSync } from 'node:child_process';
const here = dirname(fileURLToPath(import.meta.url));
const script = join(here, '../../scripts/release-kit/guard.mjs');
const prod = `name = "almizan-handasi"\nmain = "worker/index.mjs"\n[[d1_databases]]\ndatabase_name = "prod"\ndatabase_id = "PROD_ID"\n`;
const stage = `name = "almizan-handasi-staging"\nmain = "worker/index.mjs"\nworkers_dev = true\n[assets]\ndirectory = "./dist/client"\n[[d1_databases]]\ndatabase_name = "stage"\ndatabase_id = "STAGE_ID"\n[vars]\nALLOWED_ORIGIN = "https://almizan-handasi-staging.example.workers.dev"\n`;
const setup = () => {
  const dir = mkdtempSync(join(tmpdir(), 'mizan-guard-'));
  mkdirSync(join(dir, 'scripts/release-kit'), { recursive: true });
  mkdirSync(join(dir, 'dist/client/sharaa'), { recursive: true });
  copyFileSync(script, join(dir, 'scripts/release-kit/guard.mjs'));
  writeFileSync(join(dir, 'package.json'), '{"type":"module"}');
  writeFileSync(join(dir, 'wrangler.toml'), prod);
  writeFileSync(join(dir, 'wrangler.staging.toml'), stage);
  for (const p of ['home.html','home.mjs','sharaa/flow.mjs']) writeFileSync(join(dir,'dist/client',p), '/* valid */');
  return dir;
};
const run = (dir, env={}) => spawnSync(process.execPath, [join(dir,'scripts/release-kit/guard.mjs')], { cwd:dir, encoding:'utf8', env:{...process.env, GITHUB_REF_NAME:'staging-preview', MIZAN_PREVIEW_DEPLOY:'1', MIZAN_DEPLOY_TARGET:'staging', GITHUB_ACTIONS:'false', ...env} });
test('passes isolated staging with both flags', () => { const d=setup(), r=run(d); assert.equal(r.status,0,r.stderr); assert.match(r.stdout,/STAGING_PREFLIGHT_PASS_ONLY/); });
test('blocks missing flag', () => { const d=setup(); assert.equal(run(d,{MIZAN_PREVIEW_DEPLOY:''}).status,1); });
test('blocks protected branch', () => { const d=setup(); assert.equal(run(d,{GITHUB_REF_NAME:'main'}).status,1); });
test('blocks wrong event in CI', () => { const d=setup(); assert.equal(run(d,{GITHUB_ACTIONS:'true',GITHUB_EVENT_NAME:'workflow_dispatch'}).status,1); });
test('blocks production D1 reuse', () => { const d=setup(); writeFileSync(join(d,'wrangler.staging.toml'),stage.replace('STAGE_ID','PROD_ID')); assert.equal(run(d).status,1); });
test('blocks custom routes', () => { const d=setup(); writeFileSync(join(d,'wrangler.staging.toml'),stage+'\nroute = "example.com/*"\n'); assert.equal(run(d).status,1); });
test('blocks .env in client', () => { const d=setup(); writeFileSync(join(d,'dist/client/.env'),'secret'); assert.equal(run(d).status,1); });
test('blocks sealed samples', () => { const d=setup(); writeFileSync(join(d,'dist/client/SAMPLE.json'),'{}'); assert.equal(run(d).status,1); });
test('blocks private key strings', () => { const d=setup(); writeFileSync(join(d,'dist/client/home.mjs'),'const s="sk-proj-'+ 'x'.repeat(32)+'";'); assert.equal(run(d).status,1); });
test('blocks missing Sharaa asset', () => { const d=setup(); rmSync(join(d,'dist/client/sharaa/flow.mjs')); assert.equal(run(d).status,1); });
