// فحص حي لصفحة المخرجات: المرسم ← اعتمد وأخرج ← مخرجات وتكلفة وكتاب المشروع.
import http from 'node:http';
import { readFile, mkdir } from 'node:fs/promises';
import { existsSync } from 'node:fs';
import { extname, join, normalize, resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
const root = resolve(dirname(fileURLToPath(import.meta.url)), '..', 'dist'), out = process.argv[2] || '/tmp/claude-0/home-shots';
await mkdir(out, { recursive: true });
const MIME = { '.html': 'text/html; charset=utf-8', '.mjs': 'text/javascript', '.js': 'text/javascript', '.css': 'text/css', '.json': 'application/json', '.svg': 'image/svg+xml', '.png': 'image/png' };
const server = http.createServer(async (req, res) => { const f = normalize(join(root, decodeURIComponent(new URL(req.url, 'http://x').pathname))); if (!f.startsWith(root) || !existsSync(f)) { res.writeHead(404); return res.end('nf'); } res.writeHead(200, { 'content-type': MIME[extname(f)] || 'application/octet-stream' }); res.end(await readFile(f)); });
await new Promise(r => server.listen(0, '127.0.0.1', r)); const base = `http://127.0.0.1:${server.address().port}`;
const { chromium } = await import('/opt/npm-tools/node_modules/playwright/index.mjs');
const b = await chromium.launch({ executablePath: '/opt/pw-browsers/chromium', args: ['--use-gl=swiftshader', '--enable-unsafe-swiftshader', '--no-sandbox'] });
const results = []; const check = (n, ok, d = '') => { results.push(ok); console.log((ok ? 'PASS ' : 'FAIL ') + n + (d ? ' — ' + d : '')); };
const p = await (await b.newContext({ viewport: { width: 1280, height: 800 } })).newPage(); const errs = [];
p.on('console', m => { if (m.type() === 'error' && !/ERR_FAILED|fonts\.g|net::/.test(m.text())) errs.push(m.text()); }); p.on('pageerror', e => errs.push(e.message)); p.on('dialog', d => d.accept());
await p.goto(base + '/final.html'); await p.waitForSelector('.empty');
check('بلا مشروع: رسالة واضحة', (await p.locator('.empty').innerText()).includes('لا يوجد تصميم'));
await p.goto(base + '/studio.html'); await p.click('#btnExample'); await p.waitForTimeout(500);
check('زر اعتمد وأخرج ظاهر', await p.locator('#btnFinal').isVisible());
await p.click('#btnFinal'); await p.waitForURL('**/final.html'); await p.waitForSelector('#summary');
check('ملخص وأقسام', (await p.locator('.sec').count()) >= 6, String(await p.locator('.sec').count()));
check('مخطط 2D', await p.locator('#plan0 svg').count() > 0);
check('إنشائي', await p.locator('#str0 svg').count() > 0);
check('لقطة 3D محفوظة', await p.locator('#view3d img').count() > 0);
await p.fill('input[data-rate=doors]', '1500'); await p.fill('#resPct', '5'); await p.fill('#vatPct', '15');
const tot = await p.locator('#costTotal').innerText();
const doors = await p.locator('input[data-rate=doors]').evaluate(e => e.value);
check('التكلفة تُحسب بعد إدخال السعر', /الإجمالي/.test(tot) && !/NaN/.test(tot), tot.replace(/\n/g, ' | '));
await p.reload(); await p.waitForSelector('#summary');
check('الأسعار تبقى بعد إعادة التحميل', (await p.locator('input[data-rate=doors]').inputValue()) === '1500');
const dl = p.waitForEvent('download'); await p.click('#btnBook'); const d = await dl;
const path = await d.path(); const { readFileSync } = await import('node:fs'); const html = readFileSync(path, 'utf8');
check('كتاب المشروع يُنزَّل بأقسامه', /dir="rtl"/.test(html) && html.includes('كتاب المشروع') && html.includes('1,500'), d.suggestedFilename());
await p.screenshot({ path: out + '/final-top.png' }); await p.locator('#qty').scrollIntoViewIfNeeded(); await p.screenshot({ path: out + '/final-qty.png' });
check('بلا أخطاء كونسول', errs.length === 0, errs.join(' | '));
await b.close(); server.close(); process.exit(results.every(Boolean) ? 0 : 1);
